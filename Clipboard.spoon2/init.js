// Clipboard history: remembers the last 10 copies (text and images, in memory only).
// The hotkey shows them in a chooser; pick one to put it back on the clipboard and paste it.
//
// Settings (pass via `config` in hs.spoons.use, defaults are in module.exports below):
//   maxItems, maxAgeHours, thumbnailSize, chooserWidth, placeholder, skipTypes, secretTypes,
//   passwordManagerExtensions
// e.g. hs.spoons.use("Clipboard", { config: { maxItems: 25, maxAgeHours: 24 }, hotkeys: "default", start: true })

let history = [] // newest first: { text, secret? } or { image }, plus `at` (copy time, ms)
let ownChange = -1 // changeCount of our own write, so picking an entry doesn't record it again
let thumbnail = null

function copiedFromChromePasswordManager() {
    const b64 = hs.pasteboard.readData("org.chromium.source-url") // works with any Chromium based browser
    if (!b64) return false
    const url = hs.hashing.base64Decode(b64) ?? ""
    return spoon.passwordManagerExtensions.some(id => url.startsWith(`chrome-extension://${id}/`))
}

function prune() {
    history = history.filter(e => Date.now() - e.at <= spoon.maxAgeHours * 3600 * 1000)
}

function ago(at) {
    const m = Math.floor((Date.now() - at) / 60000)
    if (m < 1) return "just now"
    if (m < 60) return `${m} minute${m === 1 ? "" : "s"} ago`
    const h = Math.floor(m / 60)
    return `${h} hour${h === 1 ? "" : "s"} ago`
}

function record(changeCount) {
    if (changeCount === ownChange || spoon.skipTypes.some(t => hs.pasteboard.hasType(t))) return
    const image = hs.pasteboard.readImage()
    const text = image ? null : hs.pasteboard.readString()
    if (!image && !text) return
    if (text) history = history.filter(e => e.text !== text)
    const secret = spoon.secretTypes.some(t => hs.pasteboard.hasType(t)) || copiedFromChromePasswordManager()
    prune()
    history.unshift(image ? { image, at: Date.now() } : { text, secret, at: Date.now() })
    history.length = Math.min(history.length, spoon.maxItems)
}

function choices() {
    prune()
    return history.map((e, i) => ({ subText: ago(e.at), ...choice(e, i) }))
}

function choice(e, i) {
    return e.image
        ? { text: `Image ${Math.round(e.image.size.w)} × ${Math.round(e.image.size.h)}`, image: e.image, index: i }
        : e.secret
            ? { text: "••••••••  (password)", index: i } // fixed length: don't leak the real one
            : { text: e.text.replace(/\s+/g, " ").trim().slice(0, 200), index: i }
}

function hideThumbnail() {
    thumbnail?.destroy()
    thumbnail = null
}

// Show the image to the right of the chooser (centered, 25% from the top of the screen)
function showThumbnail(image) {
    hideThumbnail()
    const THUMB = spoon.thumbnailSize
    const f = hs.screen.main().frame // top-left origin
    const top = f.y + f.h * 0.25
    const primaryH = hs.screen.primary().fullFrame.h // canvas windows use bottom-left origin
    thumbnail = hs.canvas.create({ x: f.x + f.w * (0.5 + spoon.chooserWidth / 2) + 10, y: primaryH - top - THUMB, w: THUMB, h: THUMB })
    thumbnail.level("popUpMenu")
    thumbnail.ignoreMouseEvents(true)
    thumbnail.appendElements([
        { type: "rectangle", action: "fill", fillColor: { white: 0.15, alpha: 0.9 }, roundedRectRadii: { xRadius: 10, yRadius: 10 } },
        { type: "image", image, frame: { x: 8, y: 8, w: THUMB - 16, h: THUMB - 16 } },
    ])
    thumbnail.show()
}

const chooser = hs.chooser.create()
chooser.onSelectionChange = (_, item) => {
    const entry = item && history[item.index]
    entry?.image ? showThumbnail(entry.image) : hideThumbnail()
}
chooser.onHide = hideThumbnail
chooser.onSelect = (item) => {
    hideThumbnail()
    const entry = item && history[item.index]
    if (!entry) return
    if (entry.image) hs.pasteboard.writeImage(entry.image)
    else if (entry.secret) hs.pasteboard.writeObjects({ "public.utf8-plain-text": entry.text, "org.nspasteboard.ConcealedType": "" })
    else hs.pasteboard.writeString(entry.text)
    ownChange = hs.pasteboard.changeCount
    history = [entry, ...history.filter(e => e !== entry)]
    hs.timer.doAfter(0.1, () => hs.eventtap.keyStroke(["cmd"], "v")) // let the previous app regain focus
}

function show() {
    chooser.placeholder = spoon.placeholder
    chooser.width = spoon.chooserWidth
    chooser.setChoices(choices()).show()
}

const spoon = module.exports = {
    maxItems: 10,
    maxAgeHours: 8,
    thumbnailSize: 240, // px, image preview next to the chooser
    chooserWidth: 0.5, // fraction of the screen width
    placeholder: "Clipboard history",
    // nspasteboard.org markers: temporary content is never recorded
    skipTypes: ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "de.petermaurer.TransientPasteboardType"],
    // passwords (1Password, Bitwarden, ...) are recorded and pasteable, but shown masked
    secretTypes: ["org.nspasteboard.ConcealedType", "com.agilebits.onepassword"],
    // Chrome extension IDs of password managers
    passwordManagerExtensions: [
        "aeblfdkhhhdcdjpifhhbdiojplfjncoa", // 1Password
        "nngceckbapebfimnlniiiahkandclblb", // Bitwarden
    ],

    // Hotkey actions, bound by Hammerspoon, e.g. hs.spoons.use("Clipboard", { hotkeys: { show: [["cmd", "shift"], "v"] } })
    bindings: {
        show: { pressed: show, message: "Show clipboard history" },
    },
    defaultHotkeys: {
        show: [["ctrl", "alt", "cmd"], "v"],
    },

    start() {
        hs.pasteboard.off("change", record)
        hs.pasteboard.on("change", record)
        return this
    },
    stop() {
        hs.pasteboard.off("change", record)
        chooser.hide()
        return this
    },
}
